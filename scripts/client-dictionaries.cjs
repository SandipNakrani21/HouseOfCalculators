/* eslint-disable @typescript-eslint/no-require-imports -- Build-time TypeScript registry loader. */
// Generate separately cached locale modules, rather than embedding the same
// dictionary in the HTML and RSC segments of thousands of static pages.
require('../tests/load-typescript.cjs');
const fs = require('node:fs');
const Module = require('node:module');
const load = Module._load;
let getClientDictionary;
try {
  // This generator runs outside React; allow only the server-only marker.
  Module._load = function(name, ...args) {
    return name === 'server-only' ? {} : load.call(this, name, ...args);
  };
  ({ getClientDictionary } = require('../src/lib/i18n/index.ts'));
} finally { Module._load = load; }
const { LOCALES } = require('../src/config/locales.ts');
const dir = 'src/lib/i18n/client';
const check = process.argv.includes('--check');
function write(file, content) {
  if (check) {
    if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== content) {
      throw new Error(file + ' is stale. Run npm run metadata.');
    }
  } else { fs.mkdirSync(dir, { recursive: true }); fs.writeFileSync(file, content); }
}
for (const locale of Object.values(LOCALES)) {
  write(`${dir}/${locale.path}.json`, JSON.stringify(getClientDictionary(locale.language, locale.code)) + '\n');
  write(`${dir}/${locale.path}.tsx`, `// Generated by scripts/client-dictionaries.cjs.\n"use client";\nimport type { ReactNode } from "react";\nimport { LocaleProvider } from "@/lib/locale-context";\nimport dictionary from "./${locale.path}.json";\nexport default function Provider({ children }: { children: ReactNode }) {\n  return <LocaleProvider localeCode="${locale.code}" dictionary={dictionary}>{children}</LocaleProvider>;\n}\n`);
}
const entries = Object.values(LOCALES).map(locale => `  "${locale.code}": dynamic(() => import("./client/${locale.path}")),`).join('\n');
write('src/lib/i18n/LocaleDictionaryProvider.tsx', `// Generated by scripts/client-dictionaries.cjs.\n"use client";\nimport dynamic from "next/dynamic";\nimport type { ReactNode } from "react";\nimport type { LocaleCode } from "@/config/locales";\n\n// Keep the dynamic imports in a client boundary so each locale is code split.\n// SSR stays enabled: translations and calculator inputs are present in HTML.\nconst providers = {\n${entries}\n};\nexport function LocaleDictionaryProvider({ localeCode, children }: { localeCode: LocaleCode; children: ReactNode }) {\n  const Provider = providers[localeCode];\n  return <Provider>{children}</Provider>;\n}\n`);
console.log('Client dictionaries: ' + Object.keys(LOCALES).length + ' separate locale modules');
